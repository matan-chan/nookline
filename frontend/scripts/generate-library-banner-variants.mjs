import { mkdir, readdir, readFile, unlink, writeFile } from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const BANNERS_DIR = path.resolve(__dirname, "../public/library-banners");
const VARIANTS_DIR = path.join(BANNERS_DIR, "variants");
const GENERATED_TS = path.resolve(__dirname, "../src/pages/library/libraryBannerVariants.generated.ts");

/** Upper bounds — outputs use intrinsic width in filenames for correct srcSet `NNNw` descriptors. */
const WIDTH_TARGETS = [640, 960, 1280, 1920, 2560, 3840];
const WEBP_QUALITY = 86;
const JPEG_QUALITY = 86;
const THUMB_WIDTH = 640;

const removeVariantsForBase = async (base) => {
  let entries;
  try {
    entries = await readdir(VARIANTS_DIR);
  } catch {
    return;
  }
  const prefix = `${base}-`;
  for (const f of entries)
    if (f.startsWith(prefix) && /\.(jpe?g|webp)$/i.test(f)) await unlink(path.join(VARIANTS_DIR, f)).catch(() => {});
};

const main = async () => {
  await mkdir(VARIANTS_DIR, { recursive: true });
  const entries = await readdir(BANNERS_DIR);
  const jpgs = entries.filter((f) => /\.jpe?g$/i.test(f)).sort((a, b) => a.localeCompare(b));
  /** @type {Record<string, number[]>} */
  const manifest = {};

  for (const name of jpgs) {
    const buf = await readFile(path.join(BANNERS_DIR, name));
    const base = name.replace(/\.jpe?g$/i, "");
    await removeVariantsForBase(base);

    /** @type {Map<number, Buffer>} */
    const webpByW = new Map();
    /** @type {Map<number, Buffer>} */
    const jpegByW = new Map();

    for (const tw of WIDTH_TARGETS) {
      const r = () => sharp(buf).resize(tw, null, { withoutEnlargement: true });
      const webpOut = await r().webp({ quality: WEBP_QUALITY }).toBuffer({ resolveWithObject: true });
      const aw = webpOut.info.width;
      if (aw == null || webpByW.has(aw)) continue;
      const jpegOut = await r().jpeg({ quality: JPEG_QUALITY, mozjpeg: true }).toBuffer({ resolveWithObject: true });
      webpByW.set(aw, webpOut.data);
      jpegByW.set(aw, jpegOut.data);
    }

    const thumbR = () => sharp(buf).resize(THUMB_WIDTH, null, { withoutEnlargement: false });
    const thumbWebp = await thumbR().webp({ quality: WEBP_QUALITY }).toBuffer({ resolveWithObject: true });
    const thumbJpeg = await thumbR().jpeg({ quality: JPEG_QUALITY, mozjpeg: true }).toBuffer({ resolveWithObject: true });
    webpByW.set(THUMB_WIDTH, thumbWebp.data);
    jpegByW.set(THUMB_WIDTH, thumbJpeg.data);

    const widthsAsc = [...webpByW.keys()].sort((a, b) => a - b);
    manifest[base] = widthsAsc;

    for (const w of widthsAsc) {
      await sharp(webpByW.get(w)).toFile(path.join(VARIANTS_DIR, `${base}-${w}.webp`));
      await sharp(jpegByW.get(w)).toFile(path.join(VARIANTS_DIR, `${base}-${w}.jpg`));
    }
  }

  const lines = Object.entries(manifest)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, ws]) => `  ${JSON.stringify(k)}: [${ws.join(", ")}] as const`);
  const ts = `// Generated by scripts/generate-library-banner-variants.mjs — do not edit.\n\nexport const LIBRARY_BANNER_HERO_WIDTHS = {\n${lines.join(",\n")},\n} as const satisfies Record<string, readonly number[]>;\n`;
  await writeFile(GENERATED_TS, ts, "utf8");
};

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
